#include "gd32f30x.h"
#include "systick.h"

volatile static uint32_t delay;

/* 自由运行的系统毫秒计数 (上电起每 1ms +1, 供非阻塞状态机用) */
volatile static uint32_t g_systick_ms = 0U;

/*!
    \brief      configure systick
    \param[in]  none
    \param[out] none
    \retval     none
*/
void systick_config(void)
{
    /* setup systick timer for 1000Hz interrupts */
    if (SysTick_Config(SystemCoreClock / 1000U)){
        /* capture error */
        while(1){
        }
    }
    /* configure the systick handler priority */
    NVIC_SetPriority(SysTick_IRQn, 0x00U);
}

/*!
    \brief      delay a time in milliseconds
    \param[in]  count: count in milliseconds
    \param[out] none
    \retval     none
*/
void delay_1ms(uint32_t count)
{
    delay = count;

    while(0U != delay){
    }
}

/*!
    \brief      delay decrement
    \param[in]  none
    \param[out] none
    \retval     none
*/
void delay_decrement(void)
{
    g_systick_ms++;          /* 自由运行毫秒计数, 每次 SysTick 中断 +1 */

    if(0U != delay){
        delay--;
    }
}

/*!
    \brief      get the free-running millisecond tick since power-up
    \param[in]  none
    \param[out] none
    \retval     当前毫秒计数 (1kHz, 约 49.7 天回绕)
*/
uint32_t systick_get_ms(void)
{
    return g_systick_ms;
}
